"""Reproduce display-only compact MCS tables and an exact display binding map.

Reads one saved public report receipt. Does not import an MCS/numerical module,
read loss vectors, calculate a statistic or change a membership decision.
"""
from collections import Counter
import hashlib
import json
from pathlib import Path
import re
import sys


ROOT=Path(__file__).resolve().parents[2]
SOURCE=ROOT/'results/v10/mcs/report-values.json'
TEX=ROOT/'submission-v10/generated/v10-mcs-compact.tex'
MAP=ROOT/'notes/v10/mcs-display-map.json'
CLASS_CODES={'matched_historical':'H','other_historical':'R','conditional':'C','other_benchmark':'B'}


def tex(value):
    special={'\\':r'\textbackslash{}','&':r'\&','%':r'\%','$':r'\$','#':r'\#',
             '_':r'\_','{':r'\{','}':r'\}','~':r'\textasciitilde{}','^':r'\textasciicircum{}'}
    return ''.join(special.get(c,c) for c in str(value))


def break_tex(value):
    return ''.join(tex(p)+(r'\allowbreak{}' if p in ('::','_','-','/') else '')
                   for p in re.split(r'(::|_|-|/)',str(value)))


def build():
    raw=SOURCE.read_bytes();data=json.loads(raw);cells=data['cells']
    if len(cells)!=98:raise ValueError('display must retain all98 registered comparisons')
    groups=[g['group_label'] for g in data['groups'] if g['group_label']!='All comparisons']
    if len(groups)!=6:raise ValueError('all six source groups required')
    all_ids=set();classes={};alias_rows={}
    for cell in cells:
        all_ids.update(cell['method_ids'])
        for method,kind in cell['method_classes'].items():classes.setdefault(method,set()).add(kind)
        for item in cell['unavailable_methods']:
            all_ids.add(item['method_id'])
            if item.get('method_class'):classes.setdefault(item['method_id'],set()).add(item['method_class'])
        for item in cell.get('method_metadata',[]):
            alias_rows.setdefault(item['method_id'],[]).append(dict(identity=cell['identity'],aliases=item.get('aliases',[])))
    ordered=[m for m in ('F','I') if m in all_ids]+sorted(all_ids-{'F','I'})
    ids={m:'M'+str(i+1).zfill(2) for i,m in enumerate(ordered)};rank={m:i for i,m in enumerate(ordered)}
    legend=[dict(short_id=ids[m],method_id=m,explicit_classes=sorted(classes.get(m,set())),
                 per_comparison_storage_aliases=alias_rows.get(m,[])) for m in ordered]
    lines=[r'% Generated by notes/v10/build_mcs_compact.py; display only.',r'\begingroup',
        r'\fontsize{7.1}{8.5}\selectfont',r'\setlength{\tabcolsep}{2.15pt}',
        r'\renewcommand{\arraystretch}{1.06}',r'\setlength{\LTcapwidth}{\linewidth}',
        r'\noindent\textbf{Complete registered MCS membership and p-values.} ',
        r'All 98 source/period/$H$/$W$ comparisons are retained. Bold p-values denote included procedures using the saved literal rule $p>0.10$; ordinary type denotes exclusion. '
        r'Values are rounded to three decimals only for display. Membership uses unrounded saved values; exact p-values are public in \texttt{results/v10/mcs/report-values.json}. '
        r'\textsc{NA} denotes a known unavailable procedure, never a statistical exclusion; --- means that procedure was not registered in that particular grid. ',
        r'Multi-member exact-loss classes carry a superscript equal to the representative method ID on \emph{every} member, including the representative. Unmarked values are singleton classes. '
        r'Method IDs are display aliases only; all full labels and classifications appear in the final legend. ',
        r'The registered procedure uses 1000 stationary-bootstrap replications, confidence 0.90, statistic $R$, and block length $\max\{H,\lceil n^{1/3}\rceil\}$. '
        r'Analytic identical-loss or single-method cases retain their saved status; no new inference is performed for this table.', '']
    table_map=[];bindings=[];printed_p=printed_na=marked_members=0
    for gi,group in enumerate(groups):
        if gi:lines.append(r'\clearpage')
        selected=[c for c in cells if c['group_label']==group]
        methods=sorted({m for c in selected for m in c['method_ids']}|
                       {u['method_id'] for c in selected for u in c['unavailable_methods']},key=lambda m:rank[m])
        chunks=[methods[i:i+12] for i in range(0,len(methods),12)]
        lines.append(r'\noindent\textbf{'+tex(group)+r'.} Each method column is shown once for every row of this group.\par')
        for bi,chunk in enumerate(chunks):
            nvalues=sorted({c['n'] for c in selected if c.get('n') is not None})
            ntext=', '.join(str(n) for n in nvalues) or 'unavailable'
            cols='@{}lrr'+'r'*len(chunk)+'@{}';total=3+len(chunk)
            head=r'Source & $H$ & $W$ & '+' & '.join(r'\texttt{'+ids[m]+'}' for m in chunk)+r' \\'
            lines += [r'\begin{longtable}{'+cols+'}',
                r'\caption{'+tex(group)+'; method block '+str(bi+1)+'/'+str(len(chunks))+'. Full-grid $n='+ntext+r'$.}\\',
                r'\toprule',head,r'\midrule',r'\endfirsthead',r'\toprule',head,r'\midrule',r'\endhead',
                r'\midrule\multicolumn{'+str(total)+r'}{r}{Continued on next page}\\\endfoot',r'\bottomrule\endlastfoot']
            for cell in selected:
                identity=cell['identity'];known_na={u['method_id']:u for u in cell['unavailable_methods']}
                if set(known_na)&set(cell['method_ids']):raise ValueError('known NA overlaps a complete procedure')
                equivalence={}
                for eq in cell.get('unique_loss_groups',[]):
                    members=eq.get('members',eq.get('methods',[]));rep=eq['representative']
                    if len(members)>1:
                        for member in members:equivalence[member]=rep
                entries=[];rendered=[]
                for method in chunk:
                    entry=dict(method_id=method,short_id=ids[method],comparison_identity=identity,
                               pvalue=None,display=None,bold=False,equivalence_representative=None)
                    if method in known_na:
                        value=r'\textsc{NA}';entry.update(display='NA',status='KNOWN_NA',unavailable_metadata=known_na[method]);printed_na+=1
                    elif method not in cell['method_ids']:
                        value=r'---';entry.update(display='---',status='NOT_REGISTERED')
                    elif not cell['successful']:
                        value=r'\textsc{Fail}';entry.update(display='Fail',status=cell['status'])
                    else:
                        p=cell['pvalues'][method];included=method in cell['included']
                        if included!=(p>.1) or (method in cell['excluded'])==included:raise ValueError('literal saved membership mismatch')
                        display=f'{p:.3f}';rep=equivalence.get(method)
                        number=r'\mathbf{'+display+'}' if included else display
                        superscript=''
                        if rep is not None:
                            superscript=r'^{\mathrm{'+ids[rep]+'}}';marked_members+=1
                        value='$'+number+superscript+'$'
                        entry.update(pvalue=p,display=display,bold=included,status='INCLUDED' if included else 'EXCLUDED',
                                     equivalence_representative=None if rep is None else dict(method_id=rep,short_id=ids[rep]))
                        printed_p+=1
                    entries.append(entry);rendered.append(value)
                source=identity['normalized_source']
                lines.append(tex(source)+' & '+str(identity['horizon'])+' & '+str(identity['window'])+' & '+' & '.join(rendered)+r' \\')
                bindings.extend(entries)
            lines += [r'\end{longtable}','']
            table_map.append(dict(group_label=group,block=bi+1,blocks=len(chunks),method_ids=chunk,
                                  short_ids=[ids[m] for m in chunk],comparison_identities=[c['identity'] for c in selected]))
    lines += [r'\clearpage',r'\noindent\textbf{Complete method legend.}\par',
        r'F/I are canonical matched aliases within each comparison only; this does not equate forecasts across sources. '
        r'Class codes: H=matched historical F/I; R=other historical (rolling F); C=conditional procedure; B=other benchmark; U=unclassified known NA. '
        r'Conditional procedures retain class C even when they select infinity or share exact losses with F/I. '
        r'Superscripts identify exact full-loss classes, not semantic method mergers. Known NA IDs retain their original full spelling.',
        r'\begin{longtable}{@{}lp{118mm}l@{}}',r'\toprule',r'Short ID & Unchanged full method ID & Class \\',r'\midrule',r'\endhead']
    for item in legend:
        class_text='/'.join(CLASS_CODES[c] for c in item['explicit_classes']) or 'U'
        lines.append(r'\texttt{'+item['short_id']+'} & '+break_tex(item['method_id'])+' & '+class_text+r' \\')
    lines += [r'\bottomrule',r'\end{longtable}',
        r'\noindent The display is exhaustive but descriptive across related, overlapping tasks; it does not pool independent-source p-values or establish future risk coverage. '
        r'The machine display map preserves full-precision entries, NA metadata, every class representative and per-comparison storage aliases.',r'\endgroup','']
    expected_p=sum(len(c['pvalues']) for c in cells if c['successful'])
    expected_na=sum(len(c['unavailable_methods']) for c in cells)
    expected_marked=sum(len(eq.get('members',eq.get('methods',[]))) for c in cells if c['successful']
                        for eq in c['unique_loss_groups'] if len(eq.get('members',eq.get('methods',[])))>1)
    if (printed_p,printed_na,marked_members)!=(expected_p,expected_na,expected_marked):raise ValueError('display inventory lost a p-value, NA or exact-loss member')
    if len({(json.dumps(e['comparison_identity'],sort_keys=True),e['method_id']) for e in bindings})!=len(bindings):raise ValueError('duplicate rendered procedure slot')
    text='\n'.join(x.rstrip() for x in lines)
    mapping=dict(schema='v10-mcs-compact-display-v1',display_only=True,
        source=dict(path=str(SOURCE.relative_to(ROOT)),bytes=len(raw),sha256=hashlib.sha256(raw).hexdigest()),
        builder=dict(path=str(Path(__file__).relative_to(ROOT)),sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest()),
        output=dict(path=str(TEX.relative_to(ROOT)),bytes=len(text.encode('utf-8')),sha256=hashlib.sha256(text.encode('utf-8')).hexdigest()),
        method_legend=legend,tables=table_map,bindings=bindings,
        comparisons=[dict(identity=c['identity'],group_label=c['group_label'],status=c['status'],n=c.get('n'),
                          unique_loss_groups=c['unique_loss_groups'],unavailable_methods=c['unavailable_methods']) for c in cells],
        checks=dict(comparisons=len(cells),successful_comparisons=sum(c['successful'] for c in cells),method_ids=len(ids),
                    pvalues_printed=printed_p,known_na_printed=printed_na,exact_loss_members_superscripted=marked_members,
                    no_membership_changes=True,no_pvalue_recomputation=True,no_omitted_method_slots=True,max_method_columns=max(len(x['method_ids']) for x in table_map)),
        layout=dict(source_group_pages=len(groups),legend_pages_expected=1,target_pages='7; at most8 if the first group starts on a partly filled wrapper page',
                    rendered_page_count=None,visual_qa='pending root supplement-wrapper compile/render'))
    return text,mapping


def main():
    overwrite='--overwrite' in sys.argv[1:]
    if any(x not in ('--overwrite',) for x in sys.argv[1:]):raise SystemExit('only --overwrite is supported')
    if not overwrite and (TEX.exists() or MAP.exists()):raise FileExistsError('compact display output exists')
    text,mapping=build()
    if hashlib.sha256(SOURCE.read_bytes()).hexdigest()!=mapping['source']['sha256']:raise ValueError('source changed')
    TEX.parent.mkdir(parents=True,exist_ok=True);MAP.parent.mkdir(parents=True,exist_ok=True)
    TEX.write_text(text,encoding='utf-8');MAP.write_text(json.dumps(mapping,ensure_ascii=False,indent=2,allow_nan=False)+'\n',encoding='utf-8')
    print(json.dumps(mapping['checks'],allow_nan=False))


if __name__=='__main__':main()
